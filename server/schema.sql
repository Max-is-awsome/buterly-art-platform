CREATE TABLE IF NOT EXISTS users (id BIGSERIAL PRIMARY KEY, google_id TEXT UNIQUE NOT NULL, email TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS nodes (id BIGSERIAL PRIMARY KEY, author_id BIGINT REFERENCES users(id), data JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS ripples (parent_id BIGINT REFERENCES nodes(id), child_id BIGINT REFERENCES nodes(id), PRIMARY KEY(parent_id,child_id), CHECK(parent_id <> child_id));
CREATE INDEX IF NOT EXISTS ripples_child_idx ON ripples(child_id);
CREATE TABLE IF NOT EXISTS media (id BIGSERIAL PRIMARY KEY, author_id BIGINT NOT NULL REFERENCES users(id), mime TEXT NOT NULL, bytes BYTEA NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS drafts (user_id BIGINT PRIMARY KEY REFERENCES users(id), data JSONB NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS bookmarks (user_id BIGINT REFERENCES users(id), node_id BIGINT REFERENCES nodes(id), PRIMARY KEY(user_id,node_id));
CREATE TABLE IF NOT EXISTS reports (id BIGSERIAL PRIMARY KEY, user_id BIGINT REFERENCES users(id), node_id BIGINT REFERENCES nodes(id), reason TEXT NOT NULL, created_at TIMESTAMPTZ DEFAULT now());

CREATE TABLE IF NOT EXISTS artist_profiles (
  user_id BIGINT PRIMARY KEY REFERENCES users(id),
  display_name TEXT NOT NULL,
  bio TEXT NOT NULL DEFAULT ''
);
ALTER TABLE nodes ADD COLUMN IF NOT EXISTS show_artist BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE artist_profiles ADD COLUMN IF NOT EXISTS links JSONB NOT NULL DEFAULT '{}'::jsonb;
ALTER TABLE users ADD COLUMN IF NOT EXISTS questions_created SMALLINT NOT NULL DEFAULT 0
  CHECK (questions_created BETWEEN 0 AND 5);
